export type TranslationKeys = keyof (typeof translations)["uz-latn"];

export function getTranslations(lang: LangCode) {
  return translations[lang];
}

export function useTranslation() {
  const lang = useLanguageStore((s) => s.lang);
  return translations[lang];
}

// backward-compatible: non-reactive, reads current store value
export function getT() {
  const lang = useLanguageStore.getState().lang;
  return translations[lang];
}

// keep `t` as a reactive proxy for existing imports — but components should migrate to useTranslation()
export const t = new Proxy({} as (typeof translations)["uz-latn"], {
  get(_target, prop: string) {
    const lang = useLanguageStore.getState().lang;
    return (translations[lang] as Record<string, string>)[prop];
  },
});

export type FlowType = "Bilet" | "Topic" | "Custom" | "Exam" | "Marathon";

export function getFlowLabel(flow: string): string {
  const tr = getT();
  switch (flow) {
    case "Bilet": return tr.flowBilet;
    case "Topic": return tr.flowTopic;
    case "Custom": return tr.flowCustom;
    case "Exam": return tr.flowExam;
    case "Marathon": return tr.flowMarathon;
    default: return flow;
  }
}

export function getDurationLabel(duration: string): string {
  const tr = getT();
  switch (duration) {
    case "TwoWeeks": return tr.twoWeeks;
    case "OneMonth": return tr.oneMonth;
    case "TwoMonths": return tr.twoMonths;
    case "ThreeMonths": return tr.threeMonths;
    default: return duration;
  }
}

export function getPlanTypeLabel(type: string): string {
  const tr = getT();
  switch (type) {
    case "Student": return tr.studentPlan;
    case "Teacher": return tr.teacherPlan;
    default: return type;
  }
}
